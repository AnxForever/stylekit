export function loadStylePreview(
  styleSlug: string,
): Promise<StylePreviewComponents | null> {
  const loader = stylePreviewLoaders[styleSlug];
  if (!loader) {
    return Promise.resolve(null);
  }

  const cached = previewPromises.get(styleSlug);
  if (cached) {
    return cached;
  }

  const previewPromise = loader();
  previewPromises.set(styleSlug, previewPromise);
  return previewPromise;
}

/**
 * Warms every approved preview for the compare-only visual baseline route.
 * Normal catalog traffic stays viewport-driven and never calls this helper.
 */
export function preloadStylePreviews(): Promise<unknown> {
  if (!allPreviewsPromise) {
    allPreviewsPromise = Promise.all(
      stylePreviewSlugs.map((styleSlug) => loadStylePreview(styleSlug)),
    );
  }
  return allPreviewsPromise;
}
