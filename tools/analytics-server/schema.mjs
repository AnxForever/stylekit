import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");

/** Extract one complete, version-controlled function rather than copy its SQL. */
export function extractFunction(source, qualifiedName) {
  if (!/^[a-z_]+\.[a-z_]+$/.test(qualifiedName)) throw new Error("Invalid SQL function name");
  const prefix = `create or replace function ${qualifiedName}(`;
  const start = source.toLowerCase().indexOf(prefix);
  if (start < 0 || source.toLowerCase().indexOf(prefix, start + prefix.length) !== -1) {
    throw new Error(`Expected one source definition for ${qualifiedName}`);
  }
  const bodyStart = source.indexOf("as $$", start);
  const end = source.indexOf("\n$$;", bodyStart + 5);
  if (bodyStart < 0 || end < 0) throw new Error(`Cannot extract ${qualifiedName}`);
  return source.slice(start, end + 4);
}

export async function loadSchema(projectRoot = root) {
  const [accuracy, prompts] = await Promise.all([
    readFile(path.join(projectRoot, "lib/supabase/migrations/044_analytics_accuracy.sql"), "utf8"),
    readFile(path.join(projectRoot, "lib/supabase/migrations/043_style_prompt_copy_analytics.sql"), "utf8"),
  ]);
  const insights = extractFunction(accuracy, "public.admin_analytics_style_insights");
  const copies = extractFunction(prompts, "public.admin_analytics_prompt_copies");
  const cleanup = extractFunction(accuracy, "private.cleanup_analytics_events");

  return `-- Generated from the reviewed 043/044 report functions. Do not hand edit.
-- Apply as the owner of the dedicated stylekit_analytics database only.
-- The operator creates stylekit_analytics_runtime with separate credentials.
begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';

do $$ begin
  if current_database() <> 'stylekit_analytics' then
    raise exception 'Bootstrap requires the dedicated stylekit_analytics database';
  end if;
  if to_regrole('stylekit_analytics_runtime') is null then
    raise exception 'Create the dedicated stylekit_analytics_runtime role first';
  end if;
end $$;

revoke create on schema public from public;
create schema if not exists private;
revoke all on schema private from public, stylekit_analytics_runtime;

create table if not exists public.analytics_events (
  id bigint generated by default as identity primary key,
  event_id uuid not null unique,
  visitor_id text check (visitor_id is null or length(visitor_id) between 1 and 128),
  session_id text check (session_id is null or length(session_id) between 1 and 128),
  event_type text not null check (length(event_type) between 1 and 80),
  event_data jsonb not null check (
    jsonb_typeof(event_data) = 'object'
    and event_data @> '{"measurementVersion":2,"environment":"production"}'::jsonb
    and octet_length(event_data::text) <= 16384
  ),
  style_slug text check (style_slug is null or style_slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and length(style_slug) <= 96),
  created_at timestamptz not null
);

create index if not exists idx_analytics_created_at
  on public.analytics_events(created_at, id);
create index if not exists idx_analytics_v2_scan
  on public.analytics_events(created_at, style_slug, visitor_id)
  where event_data->>'measurementVersion' = '2'
    and event_data->>'environment' = 'production'
    and coalesce(event_data->>'deviceType', 'unknown') <> 'bot';
create index if not exists idx_analytics_prompt_copy_scan
  on public.analytics_events(created_at, style_slug, session_id)
  where event_type = 'prompt_copy';

${insights}

${copies}

${cleanup}

create or replace function public.analytics_storage_health()
returns jsonb
language sql
stable
security definer
set search_path = public, pg_catalog
as $$
select jsonb_build_object(
  'databaseBytes', pg_database_size(current_database()),
  'estimatedRows', greatest((select reltuples::bigint from pg_class where oid = 'public.analytics_events'::regclass), 0),
  'oldestEventAt', (select min(created_at) from public.analytics_events),
  'newestEventAt', (select max(created_at) from public.analytics_events)
);
$$;

revoke all on public.analytics_events from public, stylekit_analytics_runtime;
revoke all on sequence public.analytics_events_id_seq from public, stylekit_analytics_runtime;
grant usage on schema public to stylekit_analytics_runtime;
grant insert(event_id, visitor_id, session_id, event_type, event_data, style_slug, created_at)
  on public.analytics_events to stylekit_analytics_runtime;
grant select(event_id) on public.analytics_events to stylekit_analytics_runtime;
grant usage on sequence public.analytics_events_id_seq to stylekit_analytics_runtime;

revoke all on function public.admin_analytics_style_insights(timestamptz, timestamptz) from public;
revoke all on function public.admin_analytics_prompt_copies(timestamptz, timestamptz) from public;
revoke all on function public.analytics_storage_health() from public;
revoke all on function private.cleanup_analytics_events(interval, integer) from public, stylekit_analytics_runtime;
grant execute on function public.admin_analytics_style_insights(timestamptz, timestamptz) to stylekit_analytics_runtime;
grant execute on function public.admin_analytics_prompt_copies(timestamptz, timestamptz) to stylekit_analytics_runtime;
grant execute on function public.analytics_storage_health() to stylekit_analytics_runtime;
commit;
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const schema = await loadSchema();
  const output = process.argv[2];
  if (output) await writeFile(path.resolve(output), schema, { flag: "wx" });
  else process.stdout.write(schema);
}
