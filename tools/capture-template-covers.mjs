#!/usr/bin/env node
/**
 * Capture real screenshots of every template page as card covers.
 *
 * Usage:
 *   node tools/capture-template-covers.mjs [--base http://localhost:13998] [slug ...]
 *
 * Requires a running production build (`pnpm build && PORT=13998 npx next start -p 13998`).
 * Writes public/templates/covers/<slug>.webp (1280x800, q82) and regenerates
 * lib/templates/covers.generated.ts so the templates index knows which covers exist.
 */

import { chromium } from "@playwright/test";
import sharp from "sharp";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const COVERS_DIR = path.join(ROOT, "public", "templates", "covers");
const MANIFEST_PATH = path.join(ROOT, "lib", "templates", "covers.generated.ts");

const args = process.argv.slice(2);
const baseIndex = args.indexOf("--base");
const BASE = baseIndex >= 0 ? args[baseIndex + 1] : "http://localhost:13998";
const onlySlugs = args.filter((arg, i) => !arg.startsWith("--") && i !== baseIndex + 1);

async function catalogSlugs() {
  const catalog = await readFile(path.join(ROOT, "lib", "templates", "catalog.ts"), "utf-8");
  return [...catalog.matchAll(/href: "\/templates\/([a-z0-9-]+)"/g)].map((m) => m[1]);
}

async function writeManifest() {
  const files = await readdir(COVERS_DIR).catch(() => []);
  const slugs = files
    .filter((file) => file.endsWith(".webp"))
    .map((file) => file.replace(/\.webp$/, ""))
    .sort();
  const body = `// Generated by tools/capture-template-covers.mjs — do not edit by hand.
export const templateCoverSlugs = new Set<string>([
${slugs.map((slug) => `  "${slug}",`).join("\n")}
]);
`;
  await writeFile(MANIFEST_PATH, body);
  return slugs.length;
}

async function main() {
  const slugs = onlySlugs.length > 0 ? onlySlugs : await catalogSlugs();
  await mkdir(COVERS_DIR, { recursive: true });

  const browser = await chromium.launch();
  const failures = [];

  for (const slug of slugs) {
    const page = await browser.newPage({
      viewport: { width: 1440, height: 900 },
      deviceScaleFactor: 2,
      colorScheme: "light",
    });
    try {
      await page.goto(`${BASE}/templates/${slug}`, { waitUntil: "networkidle", timeout: 45000 });
      // Hide site chrome that isn't part of the template itself: the floating
      // back/download buttons and the sticky announcement banner.
      await page.addStyleTag({
        content:
          ".fixed.top-3.right-4, [data-site-announcement] { display: none !important; }",
      });
      await page.waitForTimeout(1800);
      const png = await page.screenshot({ type: "png" });
      await sharp(png)
        .resize(1280, 800, { fit: "cover", position: "top" })
        .webp({ quality: 82 })
        .toFile(path.join(COVERS_DIR, `${slug}.webp`));
      process.stdout.write(`ok   ${slug}\n`);
    } catch (error) {
      failures.push(slug);
      process.stdout.write(`FAIL ${slug}: ${String(error).split("\n")[0]}\n`);
    } finally {
      await page.close();
    }
  }

  await browser.close();
  const count = await writeManifest();
  process.stdout.write(`\nmanifest: ${count} covers\n`);
  if (failures.length > 0) {
    process.stdout.write(`failed: ${failures.join(", ")}\n`);
    process.exitCode = 1;
  }
}

main();
