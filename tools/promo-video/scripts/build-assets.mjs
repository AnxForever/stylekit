/**
 * One build step for everything the film generates from the app.
 *
 * The film renders StyleKit's own components, so three things have to be built
 * from the app before rendering:
 *
 *   1. src/catalog.ts          the 148 real palettes (used by the reveal)
 *   2. src/generated/showcase-css.ts   Tailwind compiled over the showcase files
 *   3. src/generated/showcases.ts      imports of the real showcase components
 *
 * Run after any change to the style library:  node scripts/build-assets.mjs
 */
import { writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import postcss from "postcss";
import tailwind from "@tailwindcss/postcss";

const ROOT = path.resolve(import.meta.dirname, "../../..");
const SRC = path.resolve(import.meta.dirname, "../src");
const GEN = path.join(SRC, "generated");

/** The styles the film shows. Also the set Tailwind is compiled for. */
const FEATURED_STYLES = [
  "editorial",
  "neo-brutalist",
  "art-deco",
  "ukiyo-e-digital",
  "glassmorphism",
  "swiss-poster",
  // The problem act tiles a deliberately generic page, so the film can show what
  // AI output looks like without inventing a fake one.
  "corporate-clean",
];

const toPosix = (p) => p.replace(/\\/g, "/");
const showcaseFile = (slug) => path.join(ROOT, "app/styles", slug, "showcase/_content.tsx");

mkdirSync(GEN, { recursive: true });

// ---------------------------------------------------------------------------
// 1. The catalogue: every real palette, plus the featured subsets.
// ---------------------------------------------------------------------------
const { stylesMeta } = await import("../../../lib/styles/meta-registry.ts");

const luminance = (hex) => {
  const clean = hex.replace("#", "");
  const full = clean.length === 3 ? clean.split("").map((c) => c + c).join("") : clean;
  const n = parseInt(full.slice(0, 6), 16);
  const [r, g, b] = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) => {
    const s = v / 255;
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};

const cards = stylesMeta.map((s) => ({
  slug: s.slug,
  name: s.name,
  nameEn: s.nameEn,
  category: s.category,
  primary: s.colors.primary,
  secondary: s.colors.secondary,
  accent: s.colors.accent,
  // Ink must contrast with the card paper (the style secondary colour). The
  // threshold is 0.28, not 0.45: a mid-dark paper still swallows black ink.
  inkOnPaper: luminance(s.colors.secondary) > 0.28 ? "dark" : "light",
}));

const bySlug = new Map(cards.map((c) => [c.slug, c]));
const pick = (slugs) => slugs.map((slug) => {
  const found = bySlug.get(slug);
  if (!found) throw new Error(`Catalog drift: style "${slug}" no longer exists`);
  return found;
});

const QUARTET = pick(["neo-brutalist", "editorial", "cyberpunk-neon", "scandinavian"]);
const WALL = pick(["minimalist-flat", "corporate-clean", "soft-ui", "material-design", "pastel-ui", "notion-style"]);

const catalogBody = [
  "// GENERATED by scripts/build-assets.mjs - do not edit.",
  "// Source: lib/styles/meta-registry.ts",
  "export type StyleCard = {",
  "  slug: string;",
  "  name: string;",
  "  nameEn: string;",
  "  category: string;",
  "  primary: string;",
  "  secondary: string;",
  "  accent: string[];",
  '  inkOnPaper: "dark" | "light";',
  "};",
  "",
  `export const TOTAL_STYLES = ${cards.length};`,
  "",
  `export const ALL_STYLES: StyleCard[] = ${JSON.stringify(cards, null, 2)};`,
  "",
  `export const QUARTET: StyleCard[] = ${JSON.stringify(QUARTET, null, 2)};`,
  "",
  `export const WALL: StyleCard[] = ${JSON.stringify(WALL, null, 2)};`,
  "",
].join("\n");
writeFileSync(path.join(SRC, "catalog.ts"), catalogBody);
console.log(`catalog: ${cards.length} styles`);

// ---------------------------------------------------------------------------
// 2. Tailwind, compiled by the app for exactly the files the film imports.
// ---------------------------------------------------------------------------
const sources = FEATURED_STYLES.map((s) => toPosix(showcaseFile(s)));
const cssEntry = [
  '@import "tailwindcss";',
  ...sources.map((s) => `@source "${s.replace(toPosix(ROOT) + "/", "../../../")}";`),
  '@source "../scenes/**/*.tsx";',
  '@source "../components/**/*.tsx";',
].join("\n");

const cssPath = path.join(GEN, "_entry.css");
writeFileSync(cssPath, cssEntry);
const { css } = await postcss([tailwind({ base: ROOT })]).process(cssEntry, { from: cssPath });
// Emitted as a TS module so no webpack CSS pipeline is involved.
writeFileSync(
  path.join(GEN, "showcase-css.ts"),
  `// GENERATED by scripts/build-assets.mjs - the app Tailwind build as a string.\nexport default ${JSON.stringify(css)};\n`,
);
console.log(`tailwind: ${(css.length / 1024).toFixed(0)} KB`);

// ---------------------------------------------------------------------------
// 3. The showcase manifest.
// ---------------------------------------------------------------------------
const lines = [];
lines.push("// GENERATED by scripts/build-assets.mjs - do not edit.");
lines.push("// Renders the app's real showcase components inside the film.");
lines.push('import type React from "react";');
FEATURED_STYLES.forEach((slug, i) => {
  // Relative to the manifest, extensionless: absolute paths break other checkouts,
  // and `.tsx` specifiers require allowImportingTsExtensions.
  const specifier = toPosix(path.relative(GEN, showcaseFile(slug)))
    .replace(/\.tsx?$/, "")
    .replace(/^([^.])/, "./$1");
  lines.push(`import Showcase${i} from "${specifier}";`);
});
lines.push("");
lines.push("export const SHOWCASES: Record<string, React.FC> = {");
FEATURED_STYLES.forEach((slug, i) => {
  lines.push(`  "${slug}": Showcase${i} as React.FC,`);
});
lines.push("};");
lines.push("");
lines.push(`export const SHOWCASE_SLUGS = ${JSON.stringify(FEATURED_STYLES)} as const;`);
lines.push("export type ShowcaseSlug = (typeof SHOWCASE_SLUGS)[number];");
writeFileSync(path.join(GEN, "showcases.ts"), lines.join("\n"));
console.log(`manifest: ${FEATURED_STYLES.length} showcases`);
