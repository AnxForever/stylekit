import { writeFileSync, readFileSync } from "node:fs";
import path from "node:path";
const GEN = path.resolve(import.meta.dirname, "../src/generated");
const css = readFileSync(path.join(GEN, "showcase.css"), "utf8");
writeFileSync(
  path.join(GEN, "showcase-css.ts"),
  `// GENERATED by scripts/build-assets.mjs - the app Tailwind build as a string.\nexport default ${JSON.stringify(css)};\n`,
);
console.log("css module:", (css.length / 1024).toFixed(0), "KB");
