/**
 * Renders one of the app's real showcase pages inside the film.
 *
 * This is the whole point: the product shots in this film are the product. We
 * mount the actual component, let Tailwind (compiled from the app's own theme)
 * style it, then move a 1440x900 camera window across the full page height.
 * Everything the viewer sees is the site's own markup and motion.
 *
 * Motion note: showcases reveal their content with IntersectionObserver, which
 * never fires inside a video frame. Rather than fake it, we scroll the page and
 * the reveals happen naturally as sections enter the viewport - which is also
 * what makes each style look alive rather than pasted in.
 */
import React from "react";
import { AbsoluteFill, useCurrentFrame, useVideoConfig, delayRender, continueRender } from "remotion";
// The Tailwind build is generated by scripts/build-assets.mjs, which also writes
// it as a TS module so no webpack CSS pipeline is involved.
import css from "../generated/showcase-css";
import { SHOWCASES, type ShowcaseSlug } from "../generated/showcases";
import { progress } from "../components/motion";

/** The page is rendered at desktop width and the viewport crops it. */
const PAGE_WIDTH = 1440;
const VIEW_HEIGHT = 900;

export type ShowcaseStageProps = {
  slug: ShowcaseSlug;
  /** Where the camera starts, in page pixels. */
  startScroll: number;
  /** Where it ends. Distance drives the apparent speed. */
  endScroll: number;
  /** Frames offset so several stages can share a master timeline. */
  frameOffset?: number;
  /** Zoom multiplier for emphasis punches. */
  zoom?: [number, number];
  /** Fade the page out at the end to let the next shot cut in. */
  fadeOut?: number;
};

export const ShowcaseStage: React.FC<ShowcaseStageProps> = ({
  slug,
  startScroll,
  endScroll,
  frameOffset = 0,
  zoom = [1, 1],
  fadeOut = 0,
}) => {
  const frame = Math.max(0, useCurrentFrame() + frameOffset);
  const { durationInFrames } = useVideoConfig();
  const ref = React.useRef<HTMLDivElement>(null);
  const [handle] = React.useState(() => delayRender(`showcase:${slug}`));
  const released = React.useRef(false);

  // Wait for fonts and images before the first frame is captured, otherwise the
  // serif headings render in a fallback and the shot looks wrong.
  // Remotion serves the app public dir at /public; the showcases use absolute
  // /styles/... paths. Rewriting the root once keeps the app code untouched.
  React.useEffect(() => {
    const fix = () => {
      const root = document.getElementById("sk-root");
      if (!root) return;
      root.querySelectorAll<HTMLImageElement>("img").forEach((img) => {
        const s = img.getAttribute("src") ?? "";
        if (s.startsWith("/") && !s.startsWith("/public/")) img.src = "/public" + s;
      });
    };
    fix();
    const t2 = setTimeout(fix, 300);
    const t3 = setTimeout(fix, 1200);
    return () => { clearTimeout(t2); clearTimeout(t3); };
  }, [slug]);

  React.useEffect(() => {
    const done = () => {
      if (!released.current) {
        released.current = true;
        continueRender(handle);
      }
    };
    const t = setTimeout(done, 600);
    return () => clearTimeout(t);
  }, [handle]);

  const Showcase = SHOWCASES[slug];
  const p = progress(frame, 0, Math.max(1, durationInFrames - 1), "inOut");
  const scrollY = startScroll + (endScroll - startScroll) * p;
  const z = zoom[0] + (zoom[1] - zoom[0]) * p;
  const out = fadeOut > 0 ? progress(frame, durationInFrames - fadeOut, fadeOut, "in") : 0;

  return (
    <AbsoluteFill style={{ background: "#0B0B0D", overflow: "hidden", opacity: 1 - out }}>
      <style dangerouslySetInnerHTML={{ __html: css }} />
      {/* React rewrites <base> for asset URLs: Remotion serves the app's public/
          folder under /public, so a <base> makes the showcase's absolute
          /styles/... image paths resolve there without touching app code. */}
      <div
        style={{
          position: "absolute",
          // Centred horizontally so scaling grows around the frame centre, not
          // around the page's top-left corner (which left a black band on the
          // right whenever the stage was wider than the page).
          left: "50%",
          top: 0,
          width: PAGE_WIDTH,
          marginLeft: -PAGE_WIDTH / 2,
          // The camera: a fixed-size window that translates over the page.
          transform: `translateY(${-scrollY}px) scale(${z})`,
          transformOrigin: "50% 0%",
        }}
      >
        <div id="sk-root" ref={ref} style={{ width: PAGE_WIDTH }}>
          <Showcase />
        </div>
      </div>
    </AbsoluteFill>
  );
};

/** Chrome that frames a captured page: window bar, shadow, rounded corners. */
export const BrowserFrame: React.FC<{
  children: React.ReactNode;
  x: number;
  y: number;
  width: number;
  height: number;
  scale?: number;
  label?: string;
  rotate?: number;
}> = ({ children, x, y, width, height, scale = 1, label, rotate = 0 }) => (
  <div
    style={{
      position: "absolute",
      left: x,
      top: y,
      width,
      height,
      transform: `scale(${scale}) rotate(${rotate}deg)`,
      transformOrigin: "center center",
      borderRadius: 10,
      overflow: "hidden",
      background: "#fff",
      boxShadow: "0 50px 120px rgba(0,0,0,0.6), 0 0 0 1px rgba(255,255,255,0.08)",
    }}
  >
    <div
      style={{
        height: 26,
        background: "#1B1B22",
        display: "flex",
        alignItems: "center",
        gap: 6,
        padding: "0 10px",
      }}
    >
      {["#FF5F57", "#FEBC2E", "#28C840"].map((c) => (
        <div key={c} style={{ width: 8, height: 8, borderRadius: 4, background: c, opacity: 0.85 }} />
      ))}
      {label ? (
        <div
          style={{
            marginLeft: 10,
            fontSize: 11,
            letterSpacing: "0.14em",
            color: "rgba(255,255,255,0.45)",
            fontFamily: "monospace",
            textTransform: "uppercase",
          }}
        >
          {label}
        </div>
      ) : null}
    </div>
    <div style={{ position: "relative", height: height - 26, overflow: "hidden" }}>{children}</div>
  </div>
);
