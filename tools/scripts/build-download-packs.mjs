async function checkOutputDirectory(folder) {
  let entries;
  try {
    entries = await readdir(folder, { withFileTypes: true });
  } catch (error) {
    if (error.code === "ENOENT") return;
    throw error;
  }
  for (const entry of entries) {
    const target = path.join(folder, entry.name);
    if (entry.isSymbolicLink()) throw new Error(`Unexpected symlink in output: ${target}`);
    if (entry.isDirectory()) await checkOutputDirectory(target);
    else if (!outputs.has(target)) throw new Error(`Unexpected file in owned output directory: ${target}`);
  }
}
// Validate every target before any mutation so an unexpected file or symlink
// never causes a partially regenerated catalog or asset pack.
