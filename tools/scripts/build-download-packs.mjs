function validateGlb(data, name) {
  if (data.length < 20 || data.toString("ascii", 0, 4) !== "glTF" || data.readUInt32LE(4) !== 2 || data.readUInt32LE(8) !== data.length) {
    throw new Error(`Invalid GLB header: ${name}`);
  }
  const jsonLength = data.readUInt32LE(12);
  if (data.readUInt32LE(16) !== 0x4e4f534a || jsonLength > data.length - 20) throw new Error(`Invalid GLB JSON chunk: ${name}`);
  const gltf = JSON.parse(data.toString("utf8", 20, 20 + jsonLength));
  if (gltf.asset?.version !== "2.0" || !(gltf.meshes?.length > 0)) throw new Error(`No glTF 2.0 model: ${name}`);
  if ([...(gltf.buffers ?? []), ...(gltf.images ?? [])].some((entry) => entry.uri)) {
    throw new Error(`GLB must be self-contained: ${name}`);
  }
  const binaryOffset = 20 + jsonLength;
  if (data.length < binaryOffset + 8 || data.readUInt32LE(binaryOffset + 4) !== 0x004e4942 ||
    data.readUInt32LE(binaryOffset) !== data.length - binaryOffset - 8 ||
    gltf.buffers?.length !== 1 || !Number.isSafeInteger(gltf.buffers[0].byteLength) || !(gltf.buffers[0].byteLength > 0) ||
    gltf.buffers[0].byteLength > data.length - binaryOffset - 8) {
    throw new Error(`Missing or invalid embedded geometry buffer: ${name}`);
  }
  const componentBytes = new Map([[5120, 1], [5121, 1], [5122, 2], [5123, 2], [5125, 4], [5126, 4]]);
  function geometryAccessor(index, expectedType) {
    const accessor = gltf.accessors?.[index];
    const view = gltf.bufferViews?.[accessor?.bufferView];
    const bytes = componentBytes.get(accessor?.componentType);
    const components = expectedType === "VEC3" ? 3 : 1;
    const offsets = [view?.byteOffset ?? 0, accessor?.byteOffset ?? 0];
    if (!Number.isSafeInteger(index) || index < 0 || !accessor || accessor.type !== expectedType ||
      !Number.isSafeInteger(accessor.count) || accessor.count < 1 ||
      !Number.isSafeInteger(accessor.bufferView) || accessor.bufferView < 0 ||
      !view || view.buffer !== 0 || !Number.isSafeInteger(view.byteLength) || view.byteLength <= 0 || !bytes ||
      !offsets.every((offset) => Number.isSafeInteger(offset) && offset >= 0) ||
      (view.byteStride !== undefined && (!Number.isSafeInteger(view.byteStride) || view.byteStride < bytes * components)) ||
      (view.byteOffset ?? 0) + view.byteLength > gltf.buffers[0].byteLength ||
      (accessor.byteOffset ?? 0) + (accessor.count - 1) * (view.byteStride ?? bytes * components) + bytes * components > view.byteLength) {
      throw new Error(`Invalid geometry accessor: ${name}`);
    }
    return accessor;
  }
  const meshTriangles = gltf.meshes.map((mesh) => {
    if (!mesh.primitives?.length) throw new Error(`Empty mesh: ${name}`);
    return mesh.primitives.reduce((total, primitive) => {
      if ((primitive.mode ?? 4) !== 4) throw new Error(`Expected triangle primitives: ${name}`);
      const position = geometryAccessor(primitive.attributes?.POSITION, "VEC3");
      if (position.componentType !== 5126) throw new Error(`Expected floating-point positions: ${name}`);
      const indices = primitive.indices === undefined ? undefined : geometryAccessor(primitive.indices, "SCALAR");
      if (indices && ![5121, 5123, 5125].includes(indices.componentType)) throw new Error(`Invalid index component type: ${name}`);
      const count = indices?.count ?? position.count;
      if (count % 3 !== 0) throw new Error(`Non-triangular index count: ${name}`);
      return total + count / 3;
    }, 0);
  });
  const scene = gltf.scenes?.[gltf.scene ?? 0];
  if (!scene?.nodes?.length) throw new Error(`Model has no active scene: ${name}`);
  const seen = new Set();
  function nodeTriangles(index) {
    if (seen.has(index)) throw new Error(`Repeated or cyclic scene node: ${name}`);
    seen.add(index);
    const node = gltf.nodes?.[index];
    if (!node) throw new Error(`Invalid scene node: ${name}`);
    const triangles = node.mesh === undefined ? 0 : meshTriangles[node.mesh];
    if (triangles === undefined) throw new Error(`Invalid mesh reference: ${name}`);
    return triangles + (node.children ?? []).reduce((sum, child) => sum + nodeTriangles(child), 0);
  }
  const triangles = scene.nodes.reduce((sum, index) => sum + nodeTriangles(index), 0);
  if (!triangles) throw new Error(`Model has no rendered triangles: ${name}`);
  return triangles;
}

async function preparePack(metadata, entries, previewEntries) {
  if (!allowedSlugs.has(metadata.slug) || !styles.has(metadata.style) || !themes.has(metadata.theme)) {
    throw new Error(`Unsupported 3D pack metadata: ${metadata.slug}`);
  }
  if (reports.some((report) => report.slug === metadata.slug)) throw new Error(`Duplicate pack: ${metadata.slug}`);
  if (!Number.isSafeInteger(metadata.itemCount) || metadata.itemCount < 1 ||
    ![metadata.name, metadata.description, metadata.cover?.alt].every((value) =>
      typeof value?.zh === "string" && value.zh.trim() && typeof value?.en === "string" && value.en.trim())) {
    throw new Error(`Missing localized text or invalid item count: ${metadata.slug}`);
  }
  if (entries.filter((entry) => entry.format === "GLB" && entry.role === "model").length !== metadata.itemCount) {
    throw new Error(`itemCount must match real model files: ${metadata.slug}`);
  }
  const contentRoot = path.join(root, "content/downloads", metadata.slug, version);
  const previewRoot = path.join(root, "public/download-previews", metadata.slug);
  ownedRoots.push(contentRoot, previewRoot);
  const normalized = entries.map((entry) => ({
    ...entry,
    name: safeLeaf(entry.name),
    archiveName: safeRelative(entry.archiveName ?? entry.name),
    data: Buffer.isBuffer(entry.data) ? entry.data : Buffer.from(entry.data),
  }));
  if (new Set(normalized.map((entry) => entry.name.toLowerCase())).size !== normalized.length ||
    new Set(normalized.map((entry) => entry.id)).size !== normalized.length ||
    new Set(normalized.map((entry) => entry.archiveName.toLowerCase())).size !== normalized.length) {
    throw new Error(`Duplicate file name, ID or ZIP entry: ${metadata.slug}`);
  }
  const zip = new JSZip();
  let actualTriangles = 0;
  for (const entry of normalized) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(entry.id) || entry.id === "bundle") throw new Error(`Invalid or reserved file ID: ${entry.id}`);
    const format = path.extname(entry.name).slice(1).toUpperCase();
    const expectedRole = format === "GLB" ? "model" : format === "BLEND" ? "source" : "guide";
    if (!["GLB", "BLEND", "JSON", "CSV", "MD"].includes(format) || entry.format !== format || entry.role !== expectedRole) {
      throw new Error(`File format/role does not match its extension: ${entry.name}`);
    }
    if (entry.format === "GLB") actualTriangles += validateGlb(entry.data, entry.name);
    if (entry.format === "BLEND" && (entry.data.length < 12 || !/^BLENDER[-_][vV][0-9]{3}$/.test(entry.data.toString("ascii", 0, 12)))) {
      throw new Error(`Expected an uncompressed editable Blender source: ${entry.name}`);
    }
    zip.file(entry.archiveName, entry.data, { date: zipDate, createFolders: false });
  }
  if (metadata.geometry?.triangles !== undefined && metadata.geometry.triangles !== actualTriangles) {
    throw new Error(`Triangle count differs from the active GLB scenes: ${metadata.slug} (${actualTriangles})`);
  }
  const bundle = await zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE", compressionOptions: { level: 9 }, platform: "UNIX" });
  const zipName = `${metadata.slug}-${version}.zip`;
  const allEntries = [{ id: "bundle", name: zipName, format: "ZIP", role: "bundle", data: bundle }, ...normalized];
  for (const entry of allEntries) queueOutput(path.join(contentRoot, entry.name), entry.data);
  for (const [name, data] of Object.entries(previewEntries)) {
    safeLeaf(name);
    if (!name.endsWith(".webp")) throw new Error(`Public previews must be compressed images: ${name}`);
    queueOutput(path.join(previewRoot, name), data);
  }
  const reopened = await JSZip.loadAsync(bundle, { checkCRC32: true });
  const zipEntries = Object.values(reopened.files).filter((entry) => !entry.dir);
  if (zipEntries.length !== normalized.length) throw new Error(`ZIP entry count mismatch: ${metadata.slug}`);
  for (const entry of normalized) {
    const loaded = await reopened.file(entry.archiveName)?.async("nodebuffer");
    if (!loaded || !loaded.equals(entry.data)) throw new Error(`ZIP content mismatch: ${entry.archiveName}`);
  }
  reports.push({ slug: metadata.slug, items: metadata.itemCount, zipEntries: zipEntries.length, zipBytes: bundle.length, previews: Object.keys(previewEntries).length });
  return {
    ...metadata,
    kind: "3d", version, publication: "draft", license: { status: "pending" },
    files: allEntries.map(({ id, name, format, role, data }) => ({ id, name, format, bytes: data.length, sha256: sha256(data), role })),
  };
}

