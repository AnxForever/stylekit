function argument(name, fallback) {
  const index = process.argv.indexOf(name);
  if (index < 0) return fallback;
  const value = process.argv[index + 1];
  if (!value || value.startsWith("--")) throw new Error(`${name} requires a value.`);
  return value;
}

function safeRelative(name) {
  if (typeof name !== "string" || !name || name.includes("\\") || name.includes(":") ||
    name.startsWith("/") || name.split("/").some((part) => !part || part === "." || part === "..") ||
    !/^[a-zA-Z0-9._/-]+$/.test(name)) {
    throw new Error(`Unsafe relative filename: ${name}`);
  }
  return name;
}

function safeLeaf(name) {
  safeRelative(name);
  if (name.includes("/") || name.endsWith(".") || /^(con|prn|aux|nul|com[1-9]|lpt[1-9])(?:\.|$)/i.test(name)) {
    throw new Error(`Download filename must be a portable leaf: ${name}`);
  }
  return name;
}

function inside(parent, target) {
  const relative = path.relative(parent, target);
  return relative !== "" && relative !== ".." && !relative.startsWith(`..${path.sep}`) && !path.isAbsolute(relative);
}

function queueOutput(target, data) {
  const absolute = path.resolve(target);
  if (absolute !== catalogPath && !ownedRoots.some((folder) => inside(folder, absolute))) {
    throw new Error(`Refusing to write outside owned outputs: ${absolute}`);
  }
  if (outputs.has(absolute)) throw new Error(`Duplicate output: ${absolute}`);
  outputs.set(absolute, Buffer.isBuffer(data) ? data : Buffer.from(data));
}

async function rejectSymlinkAncestors(target) {
  let current = target;
  while (current !== root) {
    if (!inside(root, current)) throw new Error(`Path escapes workspace: ${current}`);
    try {
      const status = await lstat(current);
      if (status.isSymbolicLink()) throw new Error(`Refusing symbolic-link output: ${current}`);
      if (current === target && !status.isFile()) throw new Error(`Output target must be a regular file: ${current}`);
      if (current !== target && !status.isDirectory()) throw new Error(`Output ancestor must be a directory: ${current}`);
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    current = path.dirname(current);
  }
}

