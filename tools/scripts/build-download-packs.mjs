/**
 * Build private 3D download packs and compressed previews from real source files.
 * node tools/scripts/build-download-packs.mjs [--check]
 *   [--furniture-source D:/LowPoly-Furniture-Pack]
 *   [--additional-manifest path/to/models.json]
 *
 * Additional manifest: an array of actual model packs, each containing slug,
 * style, theme, name/description { zh, en }, itemCount, optional geometry,
 * tags, styleSlugs, sourceDir, files [{ id, source, name, format, role }],
 * cover { source, alt: { zh, en } }, previews [{ source, alt: { zh, en } }].
 * File source paths are relative to sourceDir; file names are safe leaf names.
 * The manifest is a build input, not a public download catalog. Missing source
 * files fail the build; no placeholders or unverified catalog entries are made.
 * Only owned per-pack content/preview folders and catalog.ts can be written.
 * --check compares all generated bytes without writing or running Blender.
 */
